object ReportExportHelper {

    fun generateWhatsAppText(
        businessName: String,
        periodTitle: String,
        periodType: ReportPeriodType,
        reportData: FinancialReportData,
        undepositedCash: Long = 0L
    ): String {
        val sdf = SimpleDateFormat("dd/MM/yyyy HH:mm", Locale("id", "ID"))
        val now = sdf.format(Date())

        return buildString {
            appendLine("📊 *REKAP LAPORAN KEUANGAN*")
            appendLine("🏢 *${businessName.uppercase()}*")
            appendLine("━━━━━━━━━━━━━━━━━━━━━")
            appendLine("📅 *Periode:* ${periodTitle} (${periodType.label})")
            appendLine("⏰ *Dibuat pada:* $now")
            appendLine("━━━━━━━━━━━━━━━━━━━━━")
            appendLine("💰 *TOTAL PEMASUKAN:*")
            appendLine("👉 *${formatRupiah(reportData.totalRevenue)}*")
            appendLine("📦 *Total Transaksi:* ${reportData.transactionCount} Transaksi")
            appendLine("")
            appendLine("💳 *Rincian Metode Pembayaran:*")
            appendLine("• Tunai: ${formatRupiah(reportData.cashTotal)}")
            appendLine("• Transfer Bank: ${formatRupiah(reportData.transferTotal)}")
            appendLine("• QRIS: ${formatRupiah(reportData.qrisTotal)}")
            if (undepositedCash > 0) {
                appendLine("⚠️ *Uang Tunai Belum Disetor:* ${formatRupiah(undepositedCash)}")
            }
            appendLine("")
            if (reportData.staffBreakdown.isNotEmpty()) {
                appendLine("👥 *Rekapitulasi per Kasir / Kolektor:*")
                reportData.staffBreakdown.forEach { (staff, amount) ->
                    appendLine("• $staff: ${formatRupiah(amount)}")
                }
                appendLine("")
            }
            appendLine("━━━━━━━━━━━━━━━━━━━━━")
            appendLine("Generated by Billingku RT/RW Net POS")
        }
    }

    fun shareReportViaWhatsApp(
        context: Context,
        text: String
    ) {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_TEXT, text)
            setPackage("com.whatsapp")
        }
        try {
            context.startActivity(intent)
        } catch (e: Exception) {
            // Fallback to standard share chooser
            val fallbackIntent = Intent(Intent.ACTION_SEND).apply {
                type = "text/plain"
                putExtra(Intent.EXTRA_TEXT, text)
            }
            context.startActivity(Intent.createChooser(fallbackIntent, "Bagikan Rekap Laporan"))
        }
    }

    suspend fun printThermalReport(
        printerManager: BluetoothPrinterManager,
        businessName: String,
        periodTitle: String,
        periodType: ReportPeriodType,
        reportData: FinancialReportData,
        printedBy: String = "Admin"
    ): Result<String> {
        val stream = ByteArrayOutputStream()
        try {
            val sdf = SimpleDateFormat("dd/MM/yyyy HH:mm", Locale("id", "ID"))
            val now = sdf.format(Date())

            stream.write(CMD_INIT)

            // Header
            stream.write(ALIGN_CENTER)
            stream.write(BOLD_ON)
            stream.write(DOUBLE_HEIGHT_ON)
            stream.write("${businessName.take(LINE_WIDTH_58MM)}\n".toByteArray(Charsets.ISO_8859_1))
            stream.write(TEXT_NORMAL)
            stream.write("REKAP KEUANGAN ${periodType.label.uppercase()}\n".toByteArray(Charsets.ISO_8859_1))
            stream.write(BOLD_OFF)
            stream.write("Periode: $periodTitle\n".toByteArray(Charsets.ISO_8859_1))
            stream.write("Waktu: $now\n".toByteArray(Charsets.ISO_8859_1))
            stream.write("Petugas: $printedBy\n".toByteArray(Charsets.ISO_8859_1))
            stream.write("--------------------------------\n".toByteArray(Charsets.ISO_8859_1))

            // Revenue Summary
            stream.write(ALIGN_LEFT)
            stream.write(BOLD_ON)
            stream.write(formatTwoColumns("TOTAL OMZET", formatRupiah(reportData.totalRevenue)).toByteArray(Charsets.ISO_8859_1))
            stream.write(BOLD_OFF)
            stream.write(formatTwoColumns("Jumlah Transaksi", "${reportData.transactionCount} Trx").toByteArray(Charsets.ISO_8859_1))
            stream.write("--------------------------------\n".toByteArray(Charsets.ISO_8859_1))

            // Method Breakdown
            stream.write(BOLD_ON)
            stream.write("METODE PEMBAYARAN:\n".toByteArray(Charsets.ISO_8859_1))
            stream.write(BOLD_OFF)
            stream.write(formatTwoColumns("Tunai (Cash)", formatRupiah(reportData.cashTotal)).toByteArray(Charsets.ISO_8859_1))
            stream.write(formatTwoColumns("Transfer Bank", formatRupiah(reportData.transferTotal)).toByteArray(Charsets.ISO_8859_1))
            stream.write(formatTwoColumns("QRIS / Digital", formatRupiah(reportData.qrisTotal)).toByteArray(Charsets.ISO_8859_1))
            stream.write("--------------------------------\n".toByteArray(Charsets.ISO_8859_1))

            // Staff Breakdown
            if (reportData.staffBreakdown.isNotEmpty()) {
                stream.write(BOLD_ON)
                stream.write("REKAP PER KASIR / KOLEKTOR:\n".toByteArray(Charsets.ISO_8859_1))
                stream.write(BOLD_OFF)
                reportData.staffBreakdown.forEach { (staff, amount) ->
                    stream.write(formatTwoColumns(staff, formatRupiah(amount)).toByteArray(Charsets.ISO_8859_1))
                }
                stream.write("--------------------------------\n".toByteArray(Charsets.ISO_8859_1))
            }

            // Footer
            stream.write(ALIGN_CENTER)
            stream.write("Billingku RT/RW Net System\n".toByteArray(Charsets.ISO_8859_1))
            stream.write("Simpan rekap ini sbg arsip\n".toByteArray(Charsets.ISO_8859_1))
            stream.write(FEED_2_LINES)

            if (printerManager.isAutoCutEnabled()) {
                stream.write(PAPER_CUT)
            } else {
                stream.write(FEED_2_LINES)
            }

            val feed = printerManager.getFeedLines()
            for (i in 0 until feed) {
                stream.write(FEED_1_LINE)
            }

            return printerManager.printRawBytes(stream.toByteArray())
        } catch (e: Exception) {
            return Result.failure(e)
        } finally {
            stream.close()
        }
    }
}
